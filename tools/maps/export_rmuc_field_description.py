"""Generate a standalone ROS visual description from the active RMUC field references."""
from __future__ import annotations

import argparse
import json
from math import atan2, hypot
from pathlib import Path
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[2]
ARENA_FRAME = 'rmuc2027_field'


def vec(values):
    return ' '.join(f'{value:.9g}' for value in values)


def joint(robot, name, kind, parent, child, origin, axis=None, upper=None, duration=None):
    node = ET.SubElement(robot, 'joint', name=name, type=kind)
    ET.SubElement(node, 'parent', link=parent)
    ET.SubElement(node, 'child', link=child)
    ET.SubElement(node, 'origin', xyz=vec(origin), rpy='0 0 0')
    if axis is not None:
        ET.SubElement(node, 'axis', xyz=vec(axis))
        ET.SubElement(node, 'limit', lower='0', upper=f'{upper:.9g}',
                      effort='0', velocity=f'{1.5 * upper / duration:.9g}')


def box(link, center, rpy, size, material):
    visual = ET.SubElement(link, 'visual')
    ET.SubElement(visual, 'origin', xyz=vec(center), rpy=vec(rpy))
    ET.SubElement(ET.SubElement(visual, 'geometry'), 'box', size=vec(size))
    ET.SubElement(visual, 'material', name=material)


def description(armor, zones):
    robot = ET.Element('robot', name=ARENA_FRAME)
    robot.append(ET.Comment(' Generated by export_rmuc_field_description.py. Boxes are RViz visualization proxies. '))
    for name, rgba in (('red', '.8 .1 .1 1'), ('blue', '.1 .25 .9 1'), ('zone', '.07 .85 .53 .7')):
        ET.SubElement(ET.SubElement(robot, 'material', name=name), 'color', rgba=rgba)
    ET.SubElement(robot, 'link', name=ARENA_FRAME)

    panels = sorted(armor['panels'], key=lambda item: (item['side'] != 'red', item['index']))
    if [(p['side'], p['index']) for p in panels] != [(side, index) for side in ('red', 'blue') for index in range(1, 4)]:
        raise ValueError('Expected three symmetric base panels per team')

    for panel in panels:
        stem = f"rmuc2027_{panel['side']}_base_panel_{panel['index']}"
        slide, shell = stem + '_carriage', stem + '_shell'
        ET.SubElement(robot, 'link', name=slide)
        shell_link = ET.SubElement(robot, 'link', name=shell)
        box(shell_link, panel['visual_center_m'], panel.get('visual_rpy_rad', [0, 0, 0]),
            panel['visual_size_m'], panel['side'])
        joint(robot, stem + '_slide', 'prismatic', ARENA_FRAME, slide, panel['pivot_m'],
              panel['slide_axis_ros'], panel['slide_open_m'], armor['open_duration_s'])
        joint(robot, stem + '_hinge', 'revolute', slide, shell, [0, 0, 0],
              panel['hinge_axis_ros'], panel['hinge_open_rad'], armor['open_duration_s'])

    for zone in zones['zones']:
        name = f"rmuc2027_zone_{zone['id']}"
        link = ET.SubElement(robot, 'link', name=name)
        ref = zone['reference_m']
        for ring in (zone['outer_m'], *zone['holes_m']):
            for (x0, y0), (x1, y1) in zip(ring, ring[1:] + ring[:1]):
                dx, dy = x1 - x0, y1 - y0
                box(link, [(x0 + x1) / 2 - ref[0], (y0 + y1) / 2 - ref[1], .015],
                    [0, 0, atan2(dy, dx)], [hypot(dx, dy), .02, .01], 'zone')
        joint(robot, name + '_anchor', 'fixed', ARENA_FRAME, name, ref)

    ET.indent(robot)
    return '<?xml version="1.0" encoding="utf-8"?>\n' + ET.tostring(robot, encoding='unicode') + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--armor', type=Path, default=ROOT / 'assets/maps/rmuc2027/base-armor-kinematics.json')
    parser.add_argument('--zones', type=Path, default=ROOT / 'assets/maps/rmuc2027/field-zones.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'ros2_ws/src/rmsim_bridge/description/rmuc2027_field.urdf')
    args = parser.parse_args()
    result = description(json.loads(args.armor.read_text(encoding='utf-8-sig')),
                         json.loads(args.zones.read_text(encoding='utf-8-sig')))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(result, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
